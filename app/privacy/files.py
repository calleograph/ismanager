class FileError(ValueError):
    """Only messages generated by this module may cross the process boundary."""


class Projection:
    def __init__(self, limit):
        self.limit = limit
        self.size = 0
        self.lines = []
        self.secret_values = set()
        self.secret_size = 0
        self.masked_cells = 0
        self.has_table_data = False

    def remember(self, value):
        value = value.strip()
        if value and value not in self.secret_values:
            self.secret_size += len(value)
            if self.secret_size > self.limit:
                raise FileError("Содержимое секретных столбцов превышает предел обработки.")
            self.secret_values.add(value)

    def append(self, value):
        self.size += len(value) + bool(self.lines)
        if self.size > self.limit:
            limit = f"{self.limit:,}".replace(",", " ")
            raise FileError(f"Извлечённый текст превышает предел {limit} знаков. Разделите документ на части.")
        self.lines.append(value)

    def finish(self):
        text = "\n".join(self.lines)
        repeated = 0
        if self.secret_values:
            text, repeated = mask_known_values(text, self.secret_values)
            if len(text) > self.limit:
                raise FileError("Обезличенная таблица превышает предел обработки.")
        return text, self.masked_cells + repeated


def safe_text(text):
    if any(ord(c) < 32 and c not in "\r\n\t\f" for c in text):
        raise FileError("Файл содержит управляющие символы. Сохраните текст в UTF-8.")
    return text


def decode_text(data):
    for bom, codec in (
        (codecs.BOM_UTF32_LE, "utf-32"),
        (codecs.BOM_UTF32_BE, "utf-32"),
        (codecs.BOM_UTF16_LE, "utf-16"),
        (codecs.BOM_UTF16_BE, "utf-16"),
    ):
        if data.startswith(bom):
            return safe_text(data.decode(codec))
    # Exports from Windows can be UTF-16 without a byte-order mark.
    sample = data[:4096]
    if (b"\x00" in sample or b"\x04" in sample) and len(data) % 2 == 0 and len(sample) >= 4:
        for parity, encoding in ((1, "utf-16-le"), (0, "utf-16-be")):
            half = sample[parity::2]
            if half.count(0) + half.count(4) >= len(half) * 0.6:
                return safe_text(data.decode(encoding))
    try:
        return safe_text(data.decode("utf-8-sig"))
    except UnicodeDecodeError:
        from chardet import detect

        enc = (
            detect(
                data[:65536],
                include_encodings=["windows-1251", "ibm866", "koi8-r", "windows-1252"],
                no_match_encoding="windows-1251",
            )["encoding"]
            or "windows-1251"
        )
        return safe_text(data.decode(enc))


def header(value, allow_qualified):
    # Test complete, short cell captions. A free-text request mentioning a password is not a column caption.
    if len(value) > 90:
        return False
    words = "".join(c for c in value.casefold() if c.isalnum())
    if allow_qualified or re.match(r"(?i)^(?:новый|старый|временный|служебный|резервный|new|old|temporary|vpn|smtp|ldap|db)[ _-]", value.strip()):
        return bool(SECRET_HEADER.search(words))
    return bool(SECRET_HEADER.fullmatch(words))


TABLE_CAPTIONS = frozenset({
    "заявка", "номер", "фио", "логин", "пользователь", "описание", "комментарий", "почта",
    "ticket", "id", "login", "user", "username", "email", "status", "subject",
})


# Property catalogs describe the sensitivity of the value on the same row.
_ROW_TYPE = re.compile(r"(?:data )?(?:type|category|classification|kind|field)|тип(?: данных)?|категория(?: данных)?|классификация|поле|параметр")
_ROW_ACTION = re.compile(r"(?:(?:expected|required) )?(?:action|treatment)|(?:(?:ожидаемое|требуемое) )?(?:действие|обработка)")
_ROW_VALUE = re.compile(r"(?:[a-zа-яё]+ ){0,3}(?:value|значение)|образец|пример")
_HIDE = re.compile(r"маскир|скры|замен|удал|обезлич|псевдоним|выявлени|не (?:публиков|вывод|передав)|\b(?:hide|mask|redact|replace|remove|protect|pseudonym|flag for review)")
_SENSITIVE_TYPE = re.compile(r"парол|токен|ключ|сертификат|секрет|уч[её]тн|license|credential|secret|passw|token|cookie|authorization|(?:api|signing|private|access)[ _-]?key|\b(?:pin|otp|jwt|totp)\b")


class Table:
    def __init__(self, out):
        self.out = out
        self.secrets = set()
        self.started = False
        self.value_cols = set()
        self.type_cols = set()
        self.action_cols = set()

    def row(self, values, merged=None):
        # An ordinary ticket mentioning a forgotten password must not hide every later description.
        values = [str(v) if v is not None else "" for v in values]
        labels = [re.sub(r"[ _-]+", " ", v.strip().casefold()) for v in values]
        value_cols = {i for i, v in enumerate(labels) if _ROW_VALUE.fullmatch(v)}
        type_cols = {i for i, v in enumerate(labels) if _ROW_TYPE.fullmatch(v)}
        action_cols = {i for i, v in enumerate(labels) if _ROW_ACTION.fullmatch(v)}
        schema = value_cols and (type_cols or action_cols)
        header_row = not self.started or bool(set(labels) & TABLE_CAPTIONS)
        if schema:
            self.value_cols, self.type_cols, self.action_cols = value_cols, type_cols, action_cols
        row_sensitive = any(
            (col in self.type_cols and _SENSITIVE_TYPE.search(v))
            or (col in self.action_cols and _HIDE.search(v)
                and not re.search(r"(?:не |do not )(?:маскир|скры|удал|замен|mask|redact)", v))
            for col, v in enumerate(labels)
        )
        fields = []
        for col, value in enumerate(values):
            flat = re.sub(r"\r\n|[\r\n\t]", " ", value)
            if not schema and (col in self.secrets or (row_sensitive and col in self.value_cols)):
                if value.strip() and value.strip() != MASK:
                    self.out.masked_cells += 1
                    self.out.remember(value)
                    if flat != value:
                        self.out.remember(flat)
                flat = MASK if value.strip() else ""
            elif not self.value_cols and header(value, header_row):
                last = merged.get(col, col) if merged else col
                self.secrets.update(range(col, last + 1))
            fields.append(flat)
        if any(fields):
            self.started = True
            self.out.has_table_data = True
            self.out.append("\t".join(fields).rstrip("\t"))


def delimited(ext, text, out):
    stream = io.StringIO(text, newline="")
    first = stream.readline().rstrip("\r\n")
    if re.fullmatch(r"(?i)sep=[,;\t|]", first):
        delimiter = first[-1]
    else:
        stream.seek(0)
        if ext == "tsv":
            delimiter = "\t"
        else:
            try:
                delimiter = csv.Sniffer().sniff(text[:65536], delimiters=",;\t|").delimiter
            except csv.Error:
                # Sniffer needs a complete sample of equally wide rows. Trust a delimited header in ragged exports.
                delimiter = max((",", ";", "\t", "|"), key=first.count)
    csv.field_size_limit(out.limit)
    table = Table(out)
    for row in csv.reader(stream, delimiter=delimiter, strict=True):
        table.row(row)


class VisibleText(HTMLParser):
    def __init__(self, out, *, spreadsheet=False):
        super().__init__()
        self.out = out
        self.spreadsheet = spreadsheet
        self.table = None
        self.seen_table = False
        self.row = None
        self.cell = None
        self.carry = {}
        self.column = 0
        self.span = (1, 1)
        self.skip = 0
        self.parts = []

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style", "head"):
            self.skip += 1
        if self.skip:
            return
        if tag == "table":
            if self.table is not None:
                raise FileError("Вложенные таблицы HTML требуют экспорта в CSV или XLSX.")
            if self.parts:
                self.out.append("".join(self.parts))
                self.parts.clear()
            self.table = Table(self.out)
            self.seen_table = True
        elif self.table and tag == "tr":
            self.finish_row()
            self.start_row()
        elif self.table and tag in ("td", "th"):
            self.finish_cell()
            if self.row is None:
                self.start_row()
            spans = dict(attrs)
            self.span = (int(spans.get("colspan", "1")), int(spans.get("rowspan", "1")))
            if not (1 <= self.span[0] <= 16384 and 1 <= self.span[1] <= 1_048_576):
                raise FileError("Некорректный диапазон объединённых ячеек HTML.")
            self.cell = []
        elif tag in ("p", "br", "div", "li", "h1", "h2", "h3"):
            self.handle_data("\n")

    def start_row(self):
        self.column = 0
        self.row = {col: value for col, (remaining, value) in self.carry.items()}
        self.carry = {
            col: (remaining - 1, value) for col, (remaining, value) in self.carry.items() if remaining > 1
        }

    def finish_cell(self):
        if self.cell is not None:
            while self.column in self.row:
                self.column += 1
            value = "".join(self.cell).strip()
            width, height = self.span
            if self.column + width > 16384:
                raise FileError("В таблице HTML слишком много столбцов.")
            for col in range(self.column, self.column + width):
                if col in self.row:
                    raise FileError("Объединённые ячейки HTML пересекаются.")
                self.row[col] = value
                if height > 1:
                    self.carry[col] = (height - 1, value)
            self.column += width
            self.cell = None

    def finish_row(self):
        self.finish_cell()
        if self.row is not None:
            self.table.row(self.row.get(i, "") for i in range(max(self.row, default=-1) + 1))
            self.row = None

    def handle_endtag(self, tag):
        if tag in ("script", "style", "head") and self.skip:
            self.skip -= 1
        elif not self.skip and self.table:
            if tag in ("td", "th"):
                self.finish_cell()
            elif tag == "tr":
                self.finish_row()
            elif tag == "table":
                self.finish_row()
                self.table = None
                self.carry.clear()

    def handle_data(self, data):
        if not self.skip:
            if self.cell is not None:
                self.cell.append(data)
            elif self.table is None and not self.spreadsheet:
                self.parts.append(data)

    def finish(self):
        self.close()
        if self.table is not None:
            self.finish_row()
        if self.spreadsheet and not self.seen_table:
            raise FileError("В документе Excel HTML отсутствует таблица.")
        if self.parts:
            self.out.append("".join(self.parts))


def archive_limits(archive, batch):
    items = archive.infolist()
    if (
        len(items) > (8192 if batch else 2048)
        or len({i.filename for i in items}) != len(items)
        or sum(i.file_size for i in items) > (128 if batch else 32) * 1024**2
        or any(i.flag_bits & 1 or i.file_size > max(65536, i.compress_size * 1000) for i in items)
    ):
        raise FileError("Документ превышает лимиты распаковки или зашифрован.")


def localname(tag):
    return tag.rsplit("}", 1)[-1]


def cell_coordinates(ref):
    match = re.fullmatch(r"([A-Z]{1,3})([1-9][0-9]{0,6})", ref)
    if not match:
        raise FileError("Некорректный адрес ячейки Excel.")
    col = 0
    for ch in match[1]:
        col = col * 26 + ord(ch) - 64
    if col > 16384:
        raise FileError("Некорректный столбец Excel.")
    return int(match[2]), col - 1


def sheet_cells(sheet, s, shared, out):
    table = Table(out)
    merged = {}
    for area in sheet.iter(s + "mergeCell"):
        start, end = area.get("ref", "").split(":")
        rownum, col = cell_coordinates(start)
        merged.setdefault(rownum, {})[col] = cell_coordinates(end)[1]
    for number, row in enumerate(sheet.iter(s + "row"), 1):
        cells = []
        for cell in row.findall(s + "c"):
            ref = cell.get("r")
            if ref:
                _, col = cell_coordinates(ref)
                if col < len(cells):
                    raise FileError("Нарушен порядок столбцов Excel.")
                cells.extend([""] * (col - len(cells)))
            value = cell.findtext(s + "v", "")
            if cell.get("t") == "s":
                idx = int(value)
                if not 0 <= idx < len(shared):
                    raise FileError("Нарушена таблица общих строк Excel.")
                value = shared[idx]
            elif cell.get("t") == "inlineStr":
                value = "".join(t.text or "" for t in cell.iter(s + "t"))
            formula = cell.findtext(s + "f")
            if formula:
                if len(cells) in table.secrets and value:
                    out.remember(value)
                value = " ".join(filter(None, [value, formula]))
            cells.append(value)
        table.row(cells, merged.get(int(row.get("r", number))))


def xlsx(archive, out):
    def xml(name):
        return ET.fromstring(archive.read(name))

    book = xml("xl/workbook.xml")
    s = book.tag.removesuffix("workbook")
    if s not in (
        "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}",
        "{http://purl.oclc.org/ooxml/spreadsheetml/main}",
    ):
        raise FileError("Неподдерживаемый тип книги Excel.")
    rels = {}
    shared = []
    for rel in xml("xl/_rels/workbook.xml.rels"):
        typ = rel.get("Type", "").rsplit("/", 1)[-1]
        if typ not in ("sharedStrings", "worksheet", "chartsheet"):
            continue
        if rel.get("TargetMode") == "External":
            raise FileError("Внешний лист книги Excel недоступен.")
        target = rel.get("Target", "")
        path = posixpath.normpath(
            target.lstrip("/") if target.startswith("/") else posixpath.join("xl", target)
        )
        if not path.startswith("xl/"):
            raise FileError("Некорректная ссылка на лист Excel.")
        rels[rel.get("Id")] = (typ, path)
        if typ == "sharedStrings":
            shared = ["".join(t.text or "" for t in si.iter(s + "t")) for si in xml(path).iter(s + "si")]
    count = 0
    for item in book.iter(s + "sheet"):
        rid = next((v for k, v in item.attrib.items() if localname(k) == "id"), "")
        typ, path = rels[rid]
        if typ == "chartsheet":
            continue
        sheet = xml(path)
        if sheet.tag != s + "worksheet":
            raise FileError("Некорректный лист Excel.")
        out.append(item.get("name") or f"Лист {count + 1}")
        sheet_cells(sheet, s, shared, out)
        count += 1
    if not count:
        raise FileError("В таблице отсутствуют листы данных.")
    for name in archive.namelist():
        if re.fullmatch(r"xl/(?:comments\d*|comments/comment\d*)\.xml", name):
            for node in xml(name).iter(s + "comment"):
                out.append("".join(t.text or "" for t in node.iter(s + "t")))


def repeat(element, attr, limit):
    value = int(element.get(attr, "1"))
    if not 1 <= value <= limit:
        raise FileError("Число повторов в таблице превышает предел.")
    return value


def odf(archive, ext, out):
    mime = ("application/vnd.oasis.opendocument." + ("text" if ext == "odt" else "spreadsheet")).encode()
    if archive.read("mimetype").strip() != mime:
        raise FileError("Содержимое не соответствует формату OpenDocument.")
    for part in ["content.xml"] + (["styles.xml"] if "styles.xml" in archive.namelist() else []):
        root = ET.fromstring(archive.read(part))
        if ext == "ods" and part == "content.xml":
            for element in root.iter(TAB + "table"):
                out.append(element.get(TAB + "name", ""))
                table = Table(out)
                for row in element.iter(TAB + "table-row"):
                    cells = []
                    merged = {}
                    for cell in row:
                        if cell.tag not in (TAB + "table-cell", TAB + "covered-table-cell"):
                            continue
                        value = " ".join("".join(p.itertext()) for p in cell.iter(OD + "p")) or cell.get(
                            OFF + "value", ""
                        )
                        cols = repeat(cell, TAB + "number-columns-repeated", 16384)
                        span = repeat(cell, TAB + "number-columns-spanned", 16384)
                        if span > 1:
                            merged[len(cells)] = min(16383, len(cells) + span - 1)
                        if len(cells) + cols > 16384:
                            raise FileError("Слишком много столбцов в ODS.")
                        cells.extend([value] * cols)
                    if any(cells):
                        for _ in range(repeat(row, TAB + "number-rows-repeated", 1_048_576)):
                            table.row(cells, merged)
        else:
            for p in root.iter():
                if p.tag in (OD + "p", OD + "h"):
                    out.append("".join(p.itertext()))


def binary_excel(data, out):
    from python_calamine import CalamineWorkbook, SheetTypeEnum

    with CalamineWorkbook.from_filelike(io.BytesIO(data)) as book:
        count = 0
        for meta in book.sheets_metadata:
            if meta.typ != SheetTypeEnum.WorkSheet:
                continue
            sheet = book.get_sheet_by_name(meta.name)
            if sheet.width > 16384 or sheet.height * max(1, sheet.width) > max(100000, out.limit * 2):
                raise FileError("Диапазон ячеек Excel превышает предел. Удалите пустые строки и столбцы.")
            out.append(meta.name)
            table = Table(out)
            merged = {}
            col_offset = sheet.start[1] if sheet.start else 0
            for (first, col), (_, end) in sheet.merged_cell_ranges or ():
                merged.setdefault(first, {})[col - col_offset] = end - col_offset
            for number, row in enumerate(sheet.iter_rows()):
                table.row(row, merged.get(number))
            count += 1
        if not count:
            raise FileError("В книге отсутствуют листы данных.")
    return "Извлечены значения ячеек и названия листов."


def legacy_sheet(data, out):
    if data.startswith(OLE) or data[:2] in (b"\x09\x00", b"\x09\x02", b"\x09\x04", b"\x09\x08"):
        return binary_excel(data, out)
    text = decode_text(data)
    if SS[1:-1] not in text[:32768] and re.search(r"<(?:html|table)(?:\s|>)", text[:16384], re.IGNORECASE):
        parser = VisibleText(out, spreadsheet=True)
        parser.feed(text)
        parser.finish()
        return ""
    root = ET.fromstring(data)
    if root.tag != SS + "Workbook":
        raise FileError("Файл XLS должен содержать книгу Excel, XML Spreadsheet 2003 или таблицу HTML.")
    for sheet in root.findall(SS + "Worksheet"):
        table = Table(out)
        out.append(sheet.get(SS + "Name", ""))
        for row in sheet.iter(SS + "Row"):
            cells = []
            for c in row.findall(SS + "Cell"):
                col = int(c.get(SS + "Index", len(cells) + 1))
                span = int(c.get(SS + "MergeAcross", 0))
                if not len(cells) < col <= col + span <= 16384:
                    raise FileError("Нарушен порядок столбцов Excel XML.")
                cells.extend([""] * (col - len(cells) - 1))
                cell = c.find(SS + "Data")
                value = "".join(cell.itertext()) if cell is not None else c.get(SS + "Formula", "")
                cells.extend([value] * (1 + span))
            table.row(cells)
    return ""


def word_blocks(node, w, out):
    if node.tag == w + "p":
        out.append("".join(x.text or "" if x.tag in (w + "t", w + "delText", w + "instrText")
                           else "\n" if x.tag in (w + "br", w + "cr") else "\t" if x.tag == w + "tab" else ""
                           for x in node.iter()))
        return
    if node.tag != w + "tbl":
        for child in node:
            word_blocks(child, w, out)
        return
    table = Table(out)
    for tr in node:
        if tr.tag != w + "tr":
            word_blocks(tr, w, out)
            continue
        cells = tr.findall(w + "tc")
        if len(cells) == 1:
            # Code listings are often kept inside one cell spanning many paragraphs.
            word_blocks(cells[0], w, out)
            continue
        values = []
        merged = {}
        for cell in cells:
            local = Projection(out.limit)
            word_blocks(cell, w, local)
            for secret in local.secret_values:
                out.remember(secret)
            out.masked_cells += local.masked_cells
            span = cell.find("./" + w + "tcPr/" + w + "gridSpan")
            width = int(span.get(w + "val", "1")) if span is not None else 1
            if width < 1 or len(values) + width > 16384:
                raise FileError("Недопустимая ширина ячейки Word.")
            if width > 1:
                merged[len(values)] = len(values) + width - 1
            values.extend(["\n".join(local.lines)] + [""] * (width - 1))
        table.row(values, merged)


def office(ext, data, out, batch):
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        archive_limits(archive, batch)
        if ext == "xlsb":
            if "xl/workbook.bin" not in archive.namelist():
                raise FileError("Файл не является книгой XLSB.")
            return binary_excel(data, out)
        if ext in ("xlsx", "xlsm"):
            xlsx(archive, out)
        elif ext in ("ods", "odt"):
            odf(archive, ext, out)
        else:
            parts = ["word/document.xml"] + sorted(
                n
                for n in archive.namelist()
                if re.fullmatch(r"word/(header\d*|footer\d*|footnotes|endnotes|comments)\.xml", n)
            )
            for part in parts:
                root = ET.fromstring(archive.read(part))
                w = root.tag.rsplit("}", 1)[0] + "}"
                if w not in (
                    "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}",
                    "{http://purl.oclc.org/ooxml/wordprocessingml/main}",
                ):
                    raise FileError("Неподдерживаемый тип документа Word.")
                word_blocks(root, w, out)
        images = any(
            n.startswith(("word/media/", "Pictures/", "xl/media/")) and not n.endswith("/")
            for n in archive.namelist()
        )
    if images and not any(line.strip() for line in out.lines):
        raise FileError("Документ содержит только изображения. Загрузите изображения по отдельности для OCR.")
    return "Изображения внутри офисного документа опущены." if images else ""


def run_tool(args, timeout=45):
    try:
        result = subprocess.run(
            args,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            check=True,
            timeout=timeout,
            env={**os.environ, "LC_ALL": "C", "OMP_THREAD_LIMIT": "1"},
        )
    except FileNotFoundError:
        raise FileError("На сервере отсутствует программа для чтения этого формата. Обратитесь к администратору.") from None
    except (subprocess.CalledProcessError, subprocess.TimeoutExpired):
        raise FileError("Не удалось прочитать документ. Откройте его на своём устройстве, сохраните новую копию и загрузите её снова.") from None
    return result.stdout


def legacy_doc(ext, data):
    if re.match(rb"\s*\{\\rtf[0-9]", data[:64]):
        from striprtf.striprtf import rtf_to_text

        # RTF commonly mixes ASCII control words, \'hh escapes and literal bytes from ansicpg.
        codepage = re.search(rb"\\ansicpg(\d{1,5})\b", data[:4096])
        encoding = "cp" + codepage[1].decode() if codepage else "cp1252"
        # striprtf recovers malformed groups and could otherwise return only a prefix.
        depth = 0
        closed = 0
        for token in re.finditer(rb"\\(?:bin[0-9]+|[\\{}])|[{}]", data):
            marker = token[0]
            if marker.startswith(b"\\bin"):
                raise FileError("RTF с бинарным вложением требует сохранения в DOCX.")
            if marker == b"{":
                depth += 1
            elif marker == b"}":
                depth -= 1
                if depth == 0:
                    closed = token.end()
            if not 0 <= depth <= 512:
                raise FileError("Структура RTF повреждена.")
        if depth or not closed or data[closed:].strip():
            raise FileError("Структура RTF повреждена.")
        return rtf_to_text(data.decode(encoding), encoding=encoding, errors="strict")
    if ext != "doc" or not data.startswith(OLE):
        raise FileError("Содержимое не соответствует формату Word DOC или RTF.")
    import olefile

    with olefile.OleFileIO(io.BytesIO(data), raise_defects=olefile.DEFECT_INCORRECT) as document:
        fib = document.openstream("WordDocument").read(32)
        if len(fib) != 32:
            raise FileError("Заголовок документа Word повреждён.")
        if int.from_bytes(fib[10:12], "little") & 0x8100:
            raise FileError("Снимите пароль с документа Word перед загрузкой.")
    with tempfile.TemporaryDirectory(prefix="ismanager-doc-") as directory:
        path = Path(directory) / "document.doc"
        path.write_bytes(data)
        try:
            raw = run_tool(["antiword", "-m", "UTF-8.txt", "-w", "0", str(path)])
        except FileError:
            # antiword rejects even valid very short Word 97 text streams.
            raw = run_tool(["catdoc", "-w", "-d", "utf-8", str(path)])
        return raw.decode("utf-8")


def ocr(path):
    return run_tool(["tesseract", str(path), "stdout", "-l", "rus+eng"], timeout=90).decode("utf-8").strip()


def pdf_text_pages(path, count):
    options = ["-layout", "-enc", "UTF-8", str(path), "-"]
    # Parse a bounded range in one Poppler process, then hand each page to the same OCR checks.
    for first in range(1, count + 1, 16):
        last = min(first + 15, count)
        try:
            data = run_tool(["pdftotext", "-f", str(first), "-l", str(last), *options])
            pages = data.decode("utf-8").split("\f")
        except FileError:
            pages = []
        if len(pages) == last - first + 2 and not pages[-1]:
            yield from (page.strip() for page in pages[:-1])
        else:
            for number in range(first, last + 1):
                bounds = ["-f", str(number), "-l", str(number), "-nopgbrk"]
                yield run_tool(["pdftotext", *bounds, *options]).decode("utf-8").strip()


def media(ext, data, out, batch, *, inline=False):
    with tempfile.TemporaryDirectory(prefix="ismanager-ocr-") as directory:
        path = Path(directory) / ("input." + ext)
        path.write_bytes(data)
        if ext in IMAGES:
            signatures = {
                "png": b"\x89PNG\r\n\x1a\n",
                "jpeg": b"\xff\xd8\xff",
                "jpg": b"\xff\xd8\xff",
                "tif": (b"II*\x00", b"MM\x00*"),
                "tiff": (b"II*\x00", b"MM\x00*"),
            }
            if not data.startswith(signatures[ext]):
                raise FileError("Содержимое файла не соответствует формату изображения.")
            text = ocr(path)
            if inline and not text:
                from PIL import Image

                with Image.open(path) as image:
                    width, height = image.size
                    image.verify()
                text = run_tool(["tesseract", str(path), "stdout", "-l", "rus+eng", "--psm", "11"],
                                timeout=90).decode("utf-8").strip()
                if not text and width <= 512 and height <= 160:
                    return "В небольшом встроенном изображении письма OCR не распознал текст."
            if not text:
                raise FileError("OCR не смог прочитать текст. Проверьте качество изображения.")
            out.append(text)
            return "Текст распознан локально. Проверьте чтение имён и цифр."
        if b"%PDF-" not in data[:1024]:
            raise FileError("Содержимое файла не соответствует формату PDF.")
        info = run_tool(["pdfinfo", str(path)]).decode("utf-8", errors="replace")
        if re.search(r"(?mi)^Encrypted:\s*yes", info):
            raise FileError("Снимите пароль с PDF перед загрузкой.")
        pages = re.search(r"(?m)^Pages:\s*(\d+)\s*$", info)
        maximum = 300 if batch else 60
        if not pages or not 1 <= int(pages[1]) <= maximum:
            raise FileError(f"Предел для PDF — {maximum} страниц.")
        images = {
            int(i)
            for i in re.findall(rb"(?m)^\s*(\d+)\s+\d+\s+\w+\b", run_tool(["pdfimages", "-list", str(path)]))
        }
        rendered = Path(directory) / "page.png"
        had_ocr = False
        for number, native in enumerate(pdf_text_pages(path, int(pages[1])), 1):
            bounds = ["-f", str(number), "-l", str(number)]
            if native:
                out.append(native)
            if number in images or not native:
                run_tool(
                    [
                        "pdftoppm",
                        *bounds,
                        "-scale-to",
                        "3000",
                        "-singlefile",
                        "-png",
                        str(path),
                        str(rendered.with_suffix("")),
                    ]
                )
                scanned = ocr(rendered)
                if not scanned and number in images and native:
                    raise FileError("OCR не смог прочитать содержимое смешанной страницы PDF.")
                if not scanned and not native:
                    from PIL import Image

                    with Image.open(rendered) as page:
                        if page.convert("L").getextrema()[0] < 240:
                            raise FileError(
                                "OCR не смог прочитать страницу PDF. Проверьте качество изображения."
                            )
                # Keep text layers and OCR-only lines, even when a long native heading surrounds a scanned table.
                native_lines = {" ".join(line.split()).casefold() for line in native.splitlines()}
                extra = [
                    line
                    for line in scanned.splitlines()
                    if " ".join(line.split()).casefold() not in native_lines
                ]
                if extra:
                    out.append("\n".join(extra))
                had_ocr = True
        return "Использован OCR. Проверьте имена и цифры." if had_ocr else ""


def outlook(data, out, batch):
    import olefile

    if not data.startswith(OLE):
        raise FileError("Файл не является письмом Outlook MSG.")
    with olefile.OleFileIO(io.BytesIO(data)) as mail:
        if not mail.exists("__properties_version1.0"):
            raise FileError("Отсутствуют свойства письма Outlook.")

        def binary(folder, prop):
            path = folder + ["__substg1.0_" + prop]
            return mail.openstream(path).read() if mail.exists(path) else b""

        def string(folder, prop):
            wide = binary(folder, prop + "001F")
            if wide:
                return safe_text(wide.decode("utf-16-le").rstrip("\0"))
            raw = binary(folder, prop + "001E").rstrip(b"\0")
            return decode_text(raw) if raw else ""

        for prop in ("0037", "0C1A", "0C1F", "0E04", "0E03", "0E02"):
            value = string([], prop)
            if value:
                out.append(value)
        body = string([], "1000")
        if body:
            out.append(body)
        else:
            html = string([], "1013") or decode_text(binary([], "10130102"))
            if not html:
                raise FileError("Нет доступного текстового или HTML-тела письма. Экспортируйте письмо в PDF.")
            parser = VisibleText(out)
            parser.feed(html)
            parser.finish()
        notes = []
        folders = [p for p in mail.listdir(streams=False, storages=True)
                   if len(p) == 1 and p[0].startswith("__attach_version1.0_#")]
        if len(folders) > 64:
            raise FileError("В письме более 64 вложений.")
        for number, folder in enumerate(folders, 1):
            name = string(folder, "3707") or string(folder, "3704")
            ext = Path(name).suffix.lower().lstrip(".")
            payload = binary(folder, "37010102")
            if not payload or ext not in SUPPORTED or ext == "msg":
                raise FileError("Недоступное или неподдерживаемое вложение MSG. Экспортируйте его отдельно.")
            out.append(f"Вложение {number}")
            if ext in IMAGES and string(folder, "3712"):
                note = media(ext, payload, out, batch, inline=True)
            else:
                # The same projection propagates masked cell values to the entire message.
                child = Projection(out.limit)
                note = project_document(ext, payload, child, batch)
                if not any(v.strip() for v in child.lines):
                    raise FileError("Во вложении отсутствует доступный текст.")
                for value in child.secret_values:
                    out.remember(value)
                for value in child.lines:
                    out.append(value)
                out.masked_cells += child.masked_cells
            if note and note not in notes:
                notes.append(note)
        return " ".join(notes)


def project_document(ext, data, out, batch):
    note = ""
    if ext == "msg":
        note = outlook(data, out, batch)
    elif ext in OFFICE:
        note = office(ext, data, out, batch)
    elif ext == "xls":
        note = legacy_sheet(data, out)
    elif ext in ("doc", "rtf"):
        text = legacy_doc(ext, data)
        if not re.sub(r"\[pic\]", "", text, flags=re.IGNORECASE).strip():
            raise FileError("В документе Word нет читаемого текста. Загрузите изображение для OCR.")
        out.append(text)
        note = "Извлечён текст Word. Встроенные изображения требуют отдельного OCR."
    elif ext in IMAGES or ext == "pdf":
        note = media(ext, data, out, batch)
    elif ext == "xml" and "urn:schemas-microsoft-com:office:spreadsheet" in decode_text(data)[:32768]:
        note = legacy_sheet(data, out)
    elif ext in ("csv", "tsv"):
        delimited(ext, decode_text(data), out)
    elif ext in ("html", "htm"):
        parser = VisibleText(out)
        parser.feed(decode_text(data))
        parser.finish()
    else:
        out.append(decode_text(data))
    if ext in ("xlsx", "xlsm", "xlsb", "xls", "ods") and not out.has_table_data:
        raise FileError("Книга не содержит доступных для чтения ячеек.")
    return note


def extract(ext, data, *, batch=False):
    value, note, _ = _extract_with_count(ext, data, batch=batch)
    return value, note


def _extract_with_count(ext, data, *, batch):
    ext = ext.lower().lstrip(".")
    if ext not in SUPPORTED:
        raise FileError("Формат файла не поддерживается.")
    limit = BATCH_MAX_BYTES if batch else MAX_BYTES
    if not data or len(data) > limit:
        raise FileError(f"Требуется непустой файл до {limit // 1024**2} МиБ.")
    out = Projection(BATCH_MAX_TEXT if batch else MAX_TEXT)
    note = ""
    try:
        note = project_document(ext, data, out, batch)
        value, masked_count = out.finish()
        if not value.strip():
            raise FileError("Документ не содержит доступного для чтения текста.")
        return value, note, masked_count
    except FileError:
        raise
    except Exception:  # noqa: BLE001 - Third-party parser diagnostics must never contain source values.
        # Libraries may include file contents in exception messages.
        raise FileError("Файл повреждён, защищён или не соответствует выбранному формату.") from None


def extract_isolated(path, ext, *, batch=True, with_counts=False, timeout=None):
    """Read a staged file. Optionally include the number of masks applied during table extraction."""
    if not isinstance(ext, str) or ext.lower().lstrip(".") not in SUPPORTED:
        raise FileError("Формат файла не поддерживается.")
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    except OSError:
        raise FileError("Не удалось открыть загруженный файл.") from None
    info = os.fstat(fd)
    limit = BATCH_MAX_BYTES if batch else MAX_BYTES
    if not stat.S_ISREG(info.st_mode) or not 0 < info.st_size <= limit:
        os.close(fd)
        raise FileError(f"Требуется обычный непустой файл до {limit // 1024**2} МиБ.")
    with os.fdopen(fd, "rb") as source, tempfile.TemporaryDirectory(prefix="ismanager-extract-") as staging:
        args = [sys.executable, "-m", "app.privacy.files", ext]
        if batch:
            args.append("--batch")
        # New session lets the timeout reap Poppler/Tesseract too. All parser scratch files stay in staging.
        env = {"PATH": os.defpath + ":/usr/local/bin", "TMPDIR": staging, "HOME": staging, "LC_ALL": "C.UTF-8"}
        with subprocess.Popen(
            args,
            stdin=source,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            env=env,
            cwd=Path(__file__).resolve().parents[2],
            start_new_session=True,
        ) as proc:
            try:
                output, _ = proc.communicate(timeout=timeout if timeout is not None else (900 if batch else 63))
            except subprocess.TimeoutExpired:
                raise FileError("Файл превысил время обработки. Разделите материал на части.") from None
            finally:
                # A native helper may still be alive if the parser reached its CPU/memory ceiling.
                try:
                    os.killpg(proc.pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
            if proc.returncode:
                raise FileError("Файл превысил пределы обработки.")
        try:
            payload = json.loads(output)
            if "error" in payload:
                raise FileError(payload["error"])
            if with_counts:
                return payload["text"], payload["note"], payload["masked_count"]
            return payload["text"], payload["note"]
        except (ValueError, KeyError, TypeError) as exc:
            if isinstance(exc, FileError):
                raise
            raise FileError("Не удалось получить результат чтения файла.") from None


